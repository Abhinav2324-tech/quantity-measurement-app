
CREATE TABLE IF NOT EXISTS quantity_measurement_entity (
                                                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                           operation_type VARCHAR(30) NOT NULL,

    first_value DOUBLE PRECISION,
    first_measurement_type VARCHAR(30),
    first_unit VARCHAR(30),

    second_value DOUBLE PRECISION,
    second_measurement_type VARCHAR(30),
    second_unit VARCHAR(30),

    result_value DOUBLE PRECISION,
    result_measurement_type VARCHAR(30),
    result_unit VARCHAR(30),

    comparison_result BOOLEAN,
    division_result DOUBLE PRECISION,
    error_message VARCHAR(1000),

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
    );

CREATE TABLE IF NOT EXISTS quantity_measurement_history (
                                                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                            measurement_id BIGINT NOT NULL,
                                                            operation_type VARCHAR(30) NOT NULL,
    recorded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_measurement_history
    FOREIGN KEY (measurement_id)
    REFERENCES quantity_measurement_entity(id)
    ON DELETE CASCADE
    );

CREATE INDEX IF NOT EXISTS idx_measurement_operation
    ON quantity_measurement_entity(operation_type);

CREATE INDEX IF NOT EXISTS idx_measurement_type
    ON quantity_measurement_entity(first_measurement_type);

CREATE INDEX IF NOT EXISTS idx_history_measurement
    ON quantity_measurement_history(measurement_id);
